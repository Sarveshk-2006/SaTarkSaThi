@Composable
fun TrustedBankContactsScreen(
    viewModel: TelecomSafetyViewModel,
    onNavigateBack: () -> Unit
) {
    val state by viewModel.uiState.collectAsState()
    var searchQuery by remember { mutableStateOf("") }

    LaunchedEffect(Unit) {
        viewModel.loadPortalsAndHelplines()
    }

    val filtered = state.bankHelplines.filter {
        it.bank.contains(searchQuery, ignoreCase = true) ||
                it.tollFree.contains(searchQuery, ignoreCase = true) ||
                (it.description?.contains(searchQuery, ignoreCase = true) == true)
    }

    Column(
        modifier = Modifier
            .fillMaxSize()
            .background(BackgroundLight)
    ) {
        SatarkTopBar(
            title = "Trusted Bank Directory",
            subtitle = "Verified Helplines & Dispute Desks",
            canNavigateBack = true,
            onNavigateBack = onNavigateBack
        )

        LazyColumn(
            modifier = Modifier
                .fillMaxSize()
                .padding(horizontal = 16.dp),
            verticalArrangement = Arrangement.spacedBy(14.dp)
        ) {
            item {
                Spacer(modifier = Modifier.height(4.dp))
                Text(
                    text = "Authoritative Financial Contact Directory",
                    style = MaterialTheme.typography.titleMedium,
                    fontWeight = FontWeight.Bold,
                    color = TextPrimary
                )
                Text(
                    text = "All helplines are verified from Reserve Bank of India and Ministry of Home Affairs registries. Contact numbers are never generated by AI.",
                    style = MaterialTheme.typography.bodySmall,
                    color = TextSecondary
                )
            }

            // Search Bar
            item {
                OutlinedTextField(
                    value = searchQuery,
                    onValueChange = { searchQuery = it },
                    placeholder = { Text("Search by bank name (SBI, HDFC, ICICI, 1930...)") },
                    leadingIcon = { Icon(Icons.Default.Search, contentDescription = null, tint = PrimaryNavy) },
                    singleLine = true,
                    modifier = Modifier.fillMaxWidth(),
                    shape = RoundedCornerShape(10.dp)
                )
            }

            if (state.isLoading) {
                item {
                    Column(
                        modifier = Modifier
                            .fillMaxWidth()
                            .padding(32.dp),
                        horizontalAlignment = Alignment.CenterHorizontally
                    ) {
                        CircularProgressIndicator(color = PrimaryNavy)
                        Spacer(modifier = Modifier.height(10.dp))
                        Text("Loading verified helplines...", color = TextSecondary)
                    }
                }
            } else if (filtered.isEmpty()) {
                item {
                    Column(
                        modifier = Modifier
                            .fillMaxWidth()
                            .padding(32.dp),
                        horizontalAlignment = Alignment.CenterHorizontally
                    ) {
                        Text("No bank matching '$searchQuery' found.", color = TextSecondary)
                    }
                }
            } else {
                items(filtered) { helpline ->
                    IndianHelplineCard(helpline = helpline)
                }
            }

            item {
                OfficialBanner(
                    title = "Verified Financial Directory Notice",
                    message = "In case of unauthorized debit, call 1930 and your home bank nodal officer immediately within the 2-hour Golden Hour window to mark inter-bank hold."
                )
            }

            item { Spacer(modifier = Modifier.height(20.dp)) }
        }
    }
}
